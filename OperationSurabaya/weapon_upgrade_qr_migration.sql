ALTER TABLE public.match_players
ADD COLUMN IF NOT EXISTS weapon_level INTEGER NOT NULL DEFAULT 1;

ALTER TABLE public.match_players
DROP CONSTRAINT IF EXISTS match_players_weapon_level_check;
ALTER TABLE public.match_players
ADD CONSTRAINT match_players_weapon_level_check
CHECK (weapon_level BETWEEN 1 AND 4);

CREATE TABLE IF NOT EXISTS public.weapon_upgrade_stations (
    station_code TEXT PRIMARY KEY,
    station_name TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.weapon_upgrade_scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id UUID NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
    player_id UUID NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
    station_code TEXT NOT NULL REFERENCES public.weapon_upgrade_stations(station_code),
    scanned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_weapon_station_scan_per_player
        UNIQUE (match_id, player_id, station_code)
);

CREATE INDEX IF NOT EXISTS idx_weapon_upgrade_scans_match
ON public.weapon_upgrade_scans(match_id);

