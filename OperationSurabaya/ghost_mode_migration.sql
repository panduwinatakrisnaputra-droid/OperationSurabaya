-- OPERATION: SURABAYA - Ghost Mode Treasure
-- Jalankan sekali melalui Supabase SQL Editor.

-- Waktu berakhir efek Ghost Mode. NULL berarti tidak aktif.
ALTER TABLE public.match_players
ADD COLUMN IF NOT EXISTS ghost_mode_until TIMESTAMPTZ NULL;

CREATE INDEX IF NOT EXISTS idx_match_players_ghost_mode_until
ON public.match_players (match_id, ghost_mode_until);

-- QR treasure yang dapat diaktifkan admin dengan mengubah is_active/duration_seconds.
CREATE TABLE IF NOT EXISTS public.ghost_mode_stations (
    station_code TEXT PRIMARY KEY,
    station_name TEXT NOT NULL,
    duration_seconds INTEGER NOT NULL DEFAULT 30 CHECK (duration_seconds BETWEEN 1 AND 3600),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Satu treasure Ghost Mode hanya dapat diklaim satu kali oleh setiap pemain dalam satu match.
CREATE TABLE IF NOT EXISTS public.ghost_mode_scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id UUID NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
    player_id UUID NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
    station_code TEXT NOT NULL REFERENCES public.ghost_mode_stations(station_code),
    scanned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_ghost_treasure_per_player
        UNIQUE (match_id, player_id, station_code)
);

CREATE INDEX IF NOT EXISTS idx_ghost_mode_scans_match
ON public.ghost_mode_scans(match_id);

