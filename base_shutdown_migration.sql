ALTER TABLE public.matches ADD COLUMN IF NOT EXISTS winner_team_code TEXT CHECK (winner_team_code IN ('RED','BLUE','GREEN','YELLOW'));

CREATE TABLE IF NOT EXISTS public.base_shutdown_stations (
  station_code TEXT PRIMARY KEY,
  station_name TEXT NOT NULL,
  team_code TEXT NOT NULL CHECK (team_code IN ('RED','BLUE','GREEN','YELLOW')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.base_shutdowns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id UUID NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
  station_code TEXT NOT NULL REFERENCES public.base_shutdown_stations(station_code),
  attacker_team_code TEXT NOT NULL CHECK (attacker_team_code IN ('RED','BLUE','GREEN','YELLOW')),
  defender_team_code TEXT NOT NULL CHECK (defender_team_code IN ('RED','BLUE','GREEN','YELLOW')),
  player_id UUID NOT NULL REFERENCES public.players(id),
  status TEXT NOT NULL DEFAULT 'completed',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT one_base_shutdown_per_match UNIQUE(match_id),
  CONSTRAINT different_shutdown_teams CHECK(attacker_team_code <> defender_team_code)
);

